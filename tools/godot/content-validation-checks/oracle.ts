import {readFileSync,writeFileSync} from 'node:fs';
import {ContentPackInstaller,createContentCatalog,createBattleEngine,type ContentPack} from '../../../packages/battle-engine/src/index';
const original:ContentPack[]=JSON.parse(readFileSync('godot/data/content-packs.json','utf8'));
const cases:unknown[]=[];
const units=(packs:ContentPack[])=>packs.flatMap(p=>p.units??[]);
const weapons=(packs:ContentPack[])=>packs.flatMap(p=>p.weapons??[]);
const careers=(packs:ContentPack[])=>packs.flatMap(p=>p.careers??[]);
const soldier=(packs:ContentPack[])=>units(packs).find(u=>u.id==='soldier')!;
const sword=(packs:ContentPack[])=>weapons(packs).find(w=>w.id==='soldier_sword')!;
const militia=(packs:ContentPack[])=>careers(packs).find(c=>c.id==='militia')!;
function record(name:string,edit:(p:ContentPack[])=>void=()=>{}){
 const packs=structuredClone(original);edit(packs);let error:string|null=null;
 try{const content=createContentCatalog();new ContentPackInstaller(content).install(...packs);createBattleEngine({content});}catch(caught){error=(caught as Error).message;}
 cases.push({name,packs,error});
}
record('original exported catalog');
record('unit ability unsupported',p=>soldier(p).abilities.push('unknown-ability'));
record('unlearned mastery ability unsupported',p=>militia(p).masteryAbilities.push('unknown-ability'));
record('unmaterialized weapon shape unsupported',p=>weapons(p).find(w=>w.id==='dragon_breath')!.area='unknown-area');
record('weapon hit effect unsupported',p=>Object.assign(sword(p).hitEffects,[{type:'unknown-effect'}]));
record('default reaction unsupported',p=>soldier(p).defaultReaction='unknown-reaction');
record('aggregate capability issue ordering',p=>{soldier(p).abilities.push('unknown-ability');militia(p).masteryAbilities.push('unknown-mastery');sword(p).area='unknown-area';soldier(p).defaultReaction='unknown-reaction';});
record('duplicate content identifier',p=>{p[1].units=[...(p[1].units??[]),structuredClone(soldier(p))];});
record('missing movement profile',p=>soldier(p).movementClass='unknown-profile');
record('missing armor class',p=>soldier(p).armorClass='unknown-armor');
record('empty weapon list',p=>soldier(p).weapons=[]);
record('unknown weapon',p=>soldier(p).weapons=['unknown-weapon']);
record('unknown allowed formation',p=>soldier(p).formations=['unknown-formation']);
for(const value of [-1,Number.NaN,Number.POSITIVE_INFINITY])record(`unit value ${String(value)}`,p=>soldier(p).value=value);
record('unit account blank id',p=>soldier(p).resources[' ']={current:1,capacity:2});
record('unit negative account',p=>soldier(p).resources.momentum={current:-1,capacity:2});
record('unit invalid account maximum',p=>soldier(p).resources.momentum={current:3,capacity:2});
record('unit missing account capacity',p=>{const account=soldier(p).resources.momentum={current:1,capacity:null};Reflect.deleteProperty(account,'capacity');});
record('unit invalid account finite',p=>soldier(p).resources.momentum={current:Number.NaN,capacity:null});
record('unit cost zero',p=>soldier(p).recruitCosts=[{resource:'funds',amount:0}]);
record('unit cost negative',p=>soldier(p).recruitCosts=[{resource:'funds',amount:-1}]);
record('unit cost empty resource',p=>soldier(p).recruitCosts=[{resource:' ',amount:1}]);
for(const maximum of [0,Number.NaN])record(`morale maximum ${String(maximum)}`,p=>soldier(p).morale={maximum,resilience:0});
for(const resilience of [-1,1,Number.NaN])record(`morale resilience ${String(resilience)}`,p=>soldier(p).morale={maximum:100,resilience});
for(const capacity of [0,1.5,Number.NaN])record(`transport capacity ${String(capacity)}`,p=>soldier(p).transport={capacity});
record('weapon missing damage class',p=>sword(p).damageType='unknown-damage');
record('weapon unknown status',p=>sword(p).hitEffects=[{type:'addStatus',status:'unknown-status',duration:2}]);
for(const distance of [-1,1.5,Number.NaN])record(`forced distance ${String(distance)}`,p=>sword(p).hitEffects=[{type:'forcedMove',mode:'push',distance}]);
record('forced collision null',p=>Object.assign(sword(p),{hitEffects:[{type:'forcedMove',mode:'push',distance:1,collisionDamage:null}]}));
record('forced collision negative',p=>sword(p).hitEffects=[{type:'forcedMove',mode:'push',distance:1,collisionDamage:-1}]);
record('weapon cost zero',p=>sword(p).resourceCosts=[{subject:'weapon',resource:'weapon_uses',amount:0}]);
record('terrain unknown recruitment',p=>p.flatMap(pack=>pack.terrains??[])[0].produces=['unknown-unit']);
record('terrain grant zero',p=>p.flatMap(pack=>pack.terrains??[])[0].ownerTurnGrants=[{resource:'funds',amount:0}]);
for(const tier of [-1,0.5,Number.NaN])record(`career tier ${String(tier)}`,p=>militia(p).tier=tier);
record('career minimum mastery negative',p=>militia(p).minimumMastery=-1);
record('career threshold zero',p=>militia(p).masteryThreshold=0);
record('career unknown unit',p=>militia(p).unitType='unknown-unit');
record('career unknown predecessor',p=>militia(p).from=['unknown-career']);
record('career blank mastery ability',p=>militia(p).masteryAbilities=[' ']);
record('career BOM mastery ability',p=>militia(p).masteryAbilities=['\ufeff']);
record('career non-JS whitespace mastery ability',p=>militia(p).masteryAbilities=['\u0085']);
record('unit BOM account id',p=>soldier(p).resources['\ufeff']={current:1,capacity:null});
record('career cyclic predecessor',p=>militia(p).from=['ranger']);
record('career cost zero',p=>militia(p).costs=[{resource:'funds',amount:0}]);
for(const field of ['attackMultiplier','defenseDelta','movementDelta','minimumAdjacentAllies']) record(`invalid formation ${field}`,p=>{const f=p.flatMap(pack=>pack.formations??[])[0];Object.assign(f,{[field]:field==='defenseDelta'?Number.NaN:field==='attackMultiplier'?0:-0.5});});
record('tactic missing status',p=>p.flatMap(pack=>pack.tactics??[])[0].effects=[{type:'addStatus',status:'unknown-status',duration:2}]);
record('overlay missing status',p=>p.flatMap(pack=>pack.terrainOverlays??[])[0].turnStartStatus={id:'unknown-status',duration:2});
for (const value of [0,-1,Number.NaN,Number.POSITIVE_INFINITY])record(`damage matchup ${String(value)}`,p=>p.flatMap(pack=>pack.damageMatchups??[])[0].multiplier=value);
record('damage matchup duplicate',p=>{const pack=p.find(pack=>(pack.damageMatchups?.length??0)>0)!;pack.damageMatchups=[...(pack.damageMatchups??[]),structuredClone(pack.damageMatchups![0])];});
record('damage matchup coverage',p=>{for(const pack of p)if(pack.damageMatchups)pack.damageMatchups=pack.damageMatchups.filter(m=>!(m.damageType===sword(p).damageType&&m.armorClass===soldier(p).armorClass));});
record('unknown account adapter native gate',p=>soldier(p).resources['unknown-resource']={current:1,capacity:3});
record('unknown recruit resource native gate',p=>soldier(p).recruitCosts=[{resource:'unknown-resource',amount:1}]);
record('unknown mastery cost native gate',p=>militia(p).costs=[{resource:'unknown-resource',amount:1}]);
record('unknown tactic kind native gate',p=>Object.assign(p.flatMap(pack=>pack.tactics??[])[0].effects[0],{type:'unknown-tactic'}));
record('source allows fractional vision',p=>soldier(p).vision=1.5);
writeFileSync(process.argv[2]??'/tmp/empire-content-validation.json',JSON.stringify(cases));
console.log(`Generated ${cases.length} content admission fixtures`);
